    convertToGreenTheme(asciiArt) {
        // Map different characters to different green shades for Omar Rayo-style striping
        const greenMap = {
            '█': '<span style="color: var(--primary-green);">█</span>',
            '▓': '<span style="color: var(--secondary-green);">▓</span>',
            '▒': '<span style="color: var(--dark-green);">▒</span>',
            '░': '<span style="color: var(--terminal-green);">░</span>',
            ' ': ' '
        };

        return asciiArt.split('').map(char => greenMap[char] || char).join('');
    }



    addMobileToggle() {
        // Add mobile sidebar toggle button
        const toggleButton = document.createElement('button');
        toggleButton.className = 'sidebar-toggle';
        toggleButton.textContent = '☰';
        toggleButton.onclick = () => {
            const sidebar = document.querySelector('.sidebar');
            sidebar.classList.toggle('show');
        };
        document.body.appendChild(toggleButton);

        // Close sidebar when clicking outside on mobile
        document.addEventListener('click', (e) => {
            const sidebar = document.querySelector('.sidebar');
            const toggle = document.querySelector('.sidebar-toggle');
            
            if (window.innerWidth <= 768 && 
                !sidebar.contains(e.target) && 
                !toggle.contains(e.target) && 
                sidebar.classList.contains('show')) {
                sidebar.classList.remove('show');
            }
        });
    }
